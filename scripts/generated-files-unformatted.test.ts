import { expect, test } from "bun:test";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";

// A generator's check compares its output byte for byte, so a file it writes
// must never be rewritten by `bun fmt`: every tracked file that opens with a
// generated-file header has to match the formatter's ignore patterns.

const root = path.resolve(import.meta.dir, "..");
const FORMATTED = /\.(?:[cm]?[jt]sx?|json|jsonc|css|vue)$/u;
const GENERATED_HEADER =
  /\b(?:Auto-generated|AUTO-GENERATED|@generated|DO NOT EDIT|Do not edit manually)\b/u;
const HEADER_LINES = 3;

/** Files whose opening lines declare them generated but which the formatter would still rewrite. */
export const formattedGeneratedFiles = (
  files: readonly { path: string; text: string }[],
  ignorePatterns: readonly string[],
): string[] => {
  const ignored = ignorePatterns.map((pattern) => new Bun.Glob(pattern));
  return files
    .filter(
      ({ path: file, text }) =>
        FORMATTED.test(file) &&
        GENERATED_HEADER.test(text.split("\n", HEADER_LINES).join("\n")) &&
        !ignored.some((glob) => glob.match(file)),
    )
    .map(({ path: file }) => file);
};

const ignorePatterns = (): string[] => {
  const config: unknown = Bun.TOML.parse(
    readFileSync(path.join(root, "bunfig.toml"), "utf8"),
  );
  const fmt =
    typeof config === "object" && config !== null && "fmt" in config
      ? config.fmt
      : undefined;
  const patterns =
    typeof fmt === "object" && fmt !== null && "ignorePatterns" in fmt
      ? fmt.ignorePatterns
      : undefined;
  if (
    !Array.isArray(patterns) ||
    !patterns.every((pattern) => typeof pattern === "string")
  ) {
    throw new TypeError("bunfig.toml [fmt] ignorePatterns must be strings");
  }
  return patterns;
};

test("bun fmt never rewrites a tracked generated file", () => {
  const files = execFileSync("git", ["ls-files", "-z"], {
    cwd: root,
    encoding: "utf8",
  })
    .split("\0")
    .filter((file) => FORMATTED.test(file))
    .map((file) => ({
      path: file,
      text: readFileSync(path.join(root, file), "utf8"),
    }));
  expect(formattedGeneratedFiles(files, ignorePatterns())).toEqual([]);
});

test("a generated header outside the ignore patterns is reported", () => {
  const header = "// Auto-generated by scripts/x.ts. Do not edit manually.\n";
  expect(
    formattedGeneratedFiles(
      [
        { path: "packages/a/src/out.ts", text: header },
        { path: "packages/a/src/out.gen.ts", text: header },
        { path: "packages/a/src/hand.ts", text: "export {};\n" },
        { path: "packages/a/README.md", text: header },
      ],
      ["**/*.gen.*"],
    ),
  ).toEqual(["packages/a/src/out.ts"]);
});
