import { TaggedError } from "better-result";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { minVersion, validRange } from "semver";

class ConsumerNodeMinimumError extends TaggedError("ConsumerNodeMinimumError") {}

const fail = (message) => {
  throw new ConsumerNodeMinimumError({ message });
};

// Shared engineFloors limits the exception to a package and job. This projection
// tightens its minimum-major check to the exact minimum of the published range.
const projectMinimums = (mode) => {
  const root = process.cwd();
  const configuration = JSON.parse(readFileSync(path.join(root, "stll-toolchain.json"), "utf8"));
  for (const { package: packagePath, workflow, job } of configuration.engineFloors) {
    const manifest = JSON.parse(readFileSync(path.join(root, packagePath, "package.json"), "utf8"));
    const range = manifest.engines?.node;
    const minimum =
      typeof range === "string" && validRange(range) !== null ? minVersion(range) : null;
    if (minimum === null || minimum.prerelease.length !== 0) {
      fail(`${packagePath}/package.json engines.node must have a stable minimum`);
    }
    const file = path.join(root, workflow);
    const source = readFileSync(file, "utf8");
    const parsed = Bun.YAML.parse(source);
    const steps = parsed.jobs?.[job]?.steps;
    const selectors = steps?.filter((step) => step.uses?.split("@").at(0) === "actions/setup-node");
    if (selectors?.length !== 1) fail(`${workflow}:${job} must have exactly one setup-node step`);
    const selected = selectors.at(0).with;
    if (mode === "--check") {
      if (
        selected?.["node-version"] !== minimum.version ||
        selected["node-version-file"] !== undefined
      ) {
        fail(
          `${workflow}:${job} must select ${minimum.version}, derived from ${packagePath}/package.json engines.node ${range}; run bun run generate:consumer-node-minimum`,
        );
      }
      continue;
    }
    const lines = source.split("\n");
    const start = lines.indexOf(`  ${job}:`);
    if (start < 0) fail(`${workflow}:${job} must be a root workflow job`);
    const end = lines.findIndex((line, index) => index > start && /^  \S/u.test(line));
    const indexes = [];
    for (let index = start + 1; index < (end < 0 ? lines.length : end); index += 1) {
      if (/^          node-version:/u.test(lines[index])) indexes.push(index);
    }
    if (indexes.length !== 1) fail(`${workflow}:${job} must have one literal node-version input`);
    lines[indexes.at(0)] =
      `          node-version: "${minimum.version}" # Generated by bun run generate:consumer-node-minimum.`;
    writeFileSync(file, lines.join("\n"));
  }
};

if (import.meta.main) {
  try {
    const [mode, ...extra] = process.argv.slice(2);
    if ((mode !== "--check" && mode !== "--write") || extra.length !== 0) {
      fail("Usage: bun scripts/consumer-node-minimum.mjs --check|--write");
    }
    projectMinimums(mode);
  } catch (error) {
    process.stderr.write(`[consumer-node-minimum] ${error.message}\n`);
    process.exitCode = 1;
  }
}
