/**
 * Generate the all-locales catalog and independent locale entries from JSON.
 * Raw JSON stays outside the source-mirrored build graph. Generated TypeScript
 * modules retain named and default bindings for downstream bundlers.
 *
 * Usage: bun scripts/i18n-catalogs-gen.ts [--check]
 * CI checks every generated core catalog and adapter re-export for drift.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { FOLIO_LOCALES } from "../packages/core/src/i18n/messages/locales";

const messagesDir = path.resolve(
  import.meta.dir,
  "../packages/core/src/i18n/messages",
);
const outputPath = path.join(messagesDir, "catalogs.gen.ts");
const checkOnly = process.argv.includes("--check");
const normalizeLineEndings = (value: string) => value.replaceAll("\r\n", "\n");

const entries = FOLIO_LOCALES.map((locale) => {
  const json = readFileSync(path.join(messagesDir, `${locale}.json`), "utf8");
  const value = JSON.stringify(JSON.parse(json), null, 2);
  // Re-indent the JSON body so the object literal reads cleanly inside CATALOGS.
  const indented = value
    .split("\n")
    .map((line, i) => (i === 0 ? line : `  ${line}`))
    .join("\n");
  return `  ${JSON.stringify(locale)}: ${indented}`;
}).join(",\n");

const banner = `// Auto-generated by scripts/i18n-catalogs-gen.ts from the sibling *.json locale
// catalogs. Do not edit manually; run \`bun run i18n:sync\` to regenerate.
//
// The locale catalogs are inlined here (rather than imported as raw \`.json\`) so
// tsdown's \`unbundle: true\` build keeps \`.json\` out of the build graph and emits
// no malformed per-locale \`dist/i18n/messages/<locale>.js\` modules. The \`*.json\`
// files remain the source of truth the i18n tooling reads.`;

const contents = `${banner}\nexport const CATALOGS = {\n${entries},\n} as const;\n`;

type Catalog = { readonly [key: string]: string | Catalog };

const readCatalog = (locale: string): Catalog =>
  JSON.parse(readFileSync(path.join(messagesDir, `${locale}.json`), "utf8"));

/** Each key path of `catalog`, in the order a parse of it holds the keys. */
const keyPaths = (catalog: Catalog, prefix: string[] = []): string[][] =>
  Object.keys(catalog).flatMap((key) => {
    const value = catalog[key];
    return typeof value === "string"
      ? [[...prefix, key]]
      : keyPaths(value ?? {}, [...prefix, key]);
  });

const stringAt = (catalog: Catalog, keys: string[], locale: string) => {
  let value: string | Catalog | undefined = catalog;
  for (const key of keys)
    value = typeof value === "object" ? value[key] : undefined;
  if (typeof value !== "string") {
    console.error(`Error: ${locale}.json has no string at ${keys.join(".")}.`);
    process.exit(1);
  }
  return value;
};

/**
 * The first place `catalog` differs from `english` in its keys or in which
 * of them hold strings, in any key order; `undefined` when it has the same
 * shape.
 */
const shapeDifference = (
  english: Catalog,
  catalog: Catalog,
  prefix: string[] = [],
): string | undefined => {
  const englishKeys = Object.keys(english).sort();
  const keys = Object.keys(catalog).sort();
  const extra = keys.find((key) => !(key in english));
  if (extra !== undefined) return [...prefix, extra].join(".");
  const missing = englishKeys.find((key) => !(key in catalog));
  if (missing !== undefined) return [...prefix, missing].join(".");
  for (const key of englishKeys) {
    const expected = english[key];
    const value = catalog[key];
    if (typeof expected === "string" || typeof value === "string") {
      if (typeof expected !== typeof value) return [...prefix, key].join(".");
      continue;
    }
    if (expected === undefined || value === undefined) continue;
    const nested = shapeDifference(expected, value, [...prefix, key]);
    if (nested !== undefined) return nested;
  }
  return undefined;
};

const english = readCatalog("en");
const englishPaths = keyPaths(english);
const outputs = new Map([[outputPath, contents]]);

/** The English catalog's keys, each string a 0. */
const shapeOf = (catalog: Catalog): unknown =>
  Object.fromEntries(
    Object.keys(catalog).map((key) => {
      const value = catalog[key];
      return [key, typeof value === "string" ? 0 : shapeOf(value ?? {})];
    }),
  );
outputs.set(
  path.resolve(messagesDir, "../catalogShape.gen.ts"),
  `// Auto-generated by scripts/i18n-catalogs-gen.ts from en.json. Do not edit manually.
// The keys every locale catalog holds, in the English catalog's order; each
// string is a 0.
export type CatalogShape = { readonly [key: string]: 0 | CatalogShape };

export const CATALOG_SHAPE: CatalogShape = ${JSON.stringify(shapeOf(english), null, 2)};
`,
);
for (const locale of FOLIO_LOCALES) {
  const catalog = readCatalog(locale);
  if (locale === "en") {
    outputs.set(
      path.join(messagesDir, `${locale}.gen.ts`),
      `// Auto-generated by scripts/i18n-catalogs-gen.ts. Do not edit manually.
import type { FolioMessages } from "../messages";

// Keep the public declaration identical to getFolioMessages without copying every key.
export const messages: FolioMessages = ${JSON.stringify(catalog, null, 2)};
export default messages;
`,
    );
    continue;
  }
  const difference = shapeDifference(english, catalog);
  if (difference !== undefined) {
    console.error(
      `Error: ${locale}.json and en.json differ at ${difference}: every catalog holds the English catalog's keys, and no others.`,
    );
    process.exit(1);
  }
  const strings = englishPaths.map((keys) => stringAt(catalog, keys, locale));
  outputs.set(
    path.join(messagesDir, `${locale}.gen.ts`),
    `// Auto-generated by scripts/i18n-catalogs-gen.ts. Do not edit manually.
import type { FolioMessages } from "../messages";
import { localeMessages } from "../localeMessages";

// The strings in the order the English catalog holds its keys: the shape
// ships once, with English.
export const messages: FolioMessages = localeMessages(${JSON.stringify(strings, null, 2)});
export default messages;
`,
  );
}
for (const adapter of ["react", "vue"]) {
  const adapterDir = path.resolve(
    import.meta.dir,
    `../packages/${adapter}/src/i18n/messages`,
  );
  for (const locale of FOLIO_LOCALES) {
    outputs.set(
      path.join(adapterDir, `${locale}.ts`),
      `// Auto-generated by scripts/i18n-catalogs-gen.ts. Do not edit manually.
export { default, messages } from "@stll/folio-core/i18n/messages/${locale}";
`,
    );
  }
  outputs.set(
    path.join(adapterDir, "locales.ts"),
    `// Auto-generated by scripts/i18n-catalogs-gen.ts. Do not edit manually.
export { FOLIO_LOCALES, type FolioLocale } from "@stll/folio-core/i18n/messages/locales";
`,
  );
}

let drifted = false;
for (const [output, generated] of outputs) {
  if (checkOnly) {
    const existing = existsSync(output) ? readFileSync(output, "utf8") : "";
    if (normalizeLineEndings(existing) === normalizeLineEndings(generated))
      continue;
    console.error(
      `Error: ${path.relative(process.cwd(), output)} is out of sync. Run \`bun run i18n:sync\`.`,
    );
    drifted = true;
    continue;
  }
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, generated);
}
if (drifted) process.exit(1);
console.log(
  `${checkOnly ? "Checked" : "Wrote"} ${outputs.size} generated message modules`,
);
