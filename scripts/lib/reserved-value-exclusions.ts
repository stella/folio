/**
 * Slots that can carry a reserved value and that folio deliberately does not model.
 *
 * `scripts/check-reserved-value-coverage.ts` derives every candidate slot from
 * the committed schema graph and fails when one is named by neither the
 * reserved-value registry nor this list. The list is long because the schema
 * declares far more than the editable model covers, and it is grouped so that
 * one reason can be reviewed against a whole family rather than a slot at a
 * time. An exclusion for a slot that is no longer a candidate is reported as
 * dead, so the list cannot rot in place.
 *
 * A reason is a claim about folio, not an apology: it says what the slot means
 * and what folio does instead. Moving a slot out of here and into the registry
 * is how it gets modelled.
 */

